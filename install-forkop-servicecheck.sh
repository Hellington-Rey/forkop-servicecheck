if ! CAPS="$("$BIN_PATH" capabilities 2>&1)"; then
    fail "Модуль установлен, но не запускается: $CAPS"
fi

echo "$CAPS" | grep -q '"fakeip_ranges"' || fail "Неожиданный ответ модуля: $CAPS"

