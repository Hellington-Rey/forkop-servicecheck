  Из консоли:
    forkop-servicecheck list
    forkop-servicecheck run telegram,youtube
    forkop-servicecheck run all netns
    forkop-servicecheck capabilities

  Удалить:
    sh install-forkop-servicecheck.sh --uninstall

EOF

